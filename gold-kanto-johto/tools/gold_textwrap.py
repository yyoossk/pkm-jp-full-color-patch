"""文の 1行が 18文字を こえて 右の わくに はみ出す 所の 直し（MOD・追加の 直しの 文）。
   同じ 長さの まま 区切り（<LINE>・<CONT>）の 場所を 入れかえる。
   さがし方：check/textwidth 相当（tools/check/wt/textwidth.py）で 19文字 以上の 行を 出して 見つけた もの。
   <PLAYER> は 5文字で 数える（5文字の 名前で はみ出す）。"""
import jpchar

FIX = [
    # ムサシ・コジロウ（ヤドンのいど）
    ('コジロウ{72}ジョウトの　ヤドンの　シッポは<LINE>ロケットだんが　いただくぜ！',
     'コジロウ{72}ジョウトの<LINE>ヤドンの　シッポは<CONT>ロケットだんが　いただくぜ！'),
    # おかあさん（マサラタウン）
    ('おかあさん{72}となりの　オーキドはかせが<LINE>あなたを　よんでたわよ',
     'おかあさん{72}となりの<LINE>オーキドはかせが<CONT>あなたを　よんでたわよ'),
    # ふなのり（クチバ港の 船）
    ('ふなのり{72}いあいぎりで　きを　きるには<LINE>ブルーバッジが　ひつようだよ',
     'ふなのり{72}いあいぎりで<LINE>きを　きるには<CONT>ブルーバッジが　ひつようだよ'),
    ('ふなのり{72}おお　きみが　<PLAYER>か！<LINE>せんちょうから　あずかって　いるよ',
     'ふなのり{72}おお<LINE>きみが　<PLAYER>か！<CONT>せんちょうから　あずかって　いるよ'),
    ('ふなのり{72}きみが　<PLAYER>くんだね？<LINE>オーキドはかせから　きいているよ',
     'ふなのり{72}きみが<LINE><PLAYER>くんだね？<CONT>オーキドはかせから　きいているよ'),
]


def apply(g, log):
    for a, b in FIX:
        ea, eb = jpchar.encode(a), jpchar.encode(b)
        assert len(ea) == len(eb), a
        n = 0; i = g.find(ea)
        while i >= 0:
            g[i:i + len(eb)] = eb; n += 1; i = g.find(ea, i + 1)
        assert n, '見つからない：' + a
        log.append('文の 行の 長さ 直し %d か所：%s' % (n, b.split('<')[0]))
