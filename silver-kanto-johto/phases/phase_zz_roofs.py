"""カントーの 町の 屋根の 色を 赤フルカラーと 同じに（RoofPals $02:$7934、グループごとに 昼 2色・夜 2色）。
   赤フルカラーと 同じ 戸の 前に 立って くらべた（BG パレット 6）。銀の 色の ままで、たとえば クチバは 赤い 屋根が 黄土色、
   タマムシは みどりと オレンジ だった。昼は 赤フルカラーの 色を その まま、夜は 0.6 倍に する（赤には 夜が ない）。"""

TAB = 2 * 0x4000 + 0x7934 - 0x4000
RED = {  # グループ: (色1, 色2)  RGB 0〜31
    13: ((31, 31, 31), (24, 24, 24)),   # マサラ
    23: ((0, 29, 7), (0, 24, 7)),       # トキワ
    14: ((24, 25, 26), (20, 17, 19)),   # ニビ
    7: ((14, 24, 31), (14, 20, 26)),    # ハナダ
    12: ((29, 8, 0), (22, 8, 0)),       # クチバ
    18: ((23, 12, 31), (19, 9, 24)),    # シオン
    21: ((15, 26, 19), (3, 20, 11)),    # タマムシ
    17: ((31, 3, 18), (25, 3, 12)),     # セキチク
    25: ((31, 27, 0), (28, 22, 0)),     # ヤマブキ
    6: ((29, 0, 0), (22, 0, 0)),        # グレン
}


def w(c):
    v = c[0] | c[1] << 5 | c[2] << 10
    return bytes([v & 0xff, v >> 8])


def apply(rom, ctx):
    log = ctx.setdefault('log', [])
    assert rom[TAB + 8 * 12:TAB + 8 * 12 + 4] == w((27, 23, 1)) + w((23, 11, 0))      # クチバ（銀）
    for gr, (a, b) in RED.items():
        night = [tuple(int(v * 0.6) for v in c) for c in (a, b)]
        rom[TAB + 8 * gr:TAB + 8 * gr + 8] = w(a) + w(b) + w(night[0]) + w(night[1])
    log.append('カントーの 屋根の 色を 赤フルカラーと 同じに（%d 町）' % len(RED))
    return rom
